#' @importFrom grumpy convert_bytes_to_array
codec_bytes_decode <- function(
  input,
  chunk_dim,
  datatype,
  endian
) {
  convert_bytes_to_array(
    input,
    datatype$base_type,
    chunk_dim,
    datatype$nbytes,
    endian
  )
}

codec_bytes_encode <- function(input, datatype, endian) {
  if (is.character(input)) {
    ## we need to create fixed length strings either via padding or trimming
    if (datatype$base_type == "unicode") {
      to <- ifelse(endian == "little", "UCS-4LE", "UCS-4BE")
      raw_list <- iconv(input, to = to, toRaw = TRUE)
    } else {
      raw_list <- iconv(input, toRaw = TRUE)
    }
    unlist(
      lapply(
        raw_list,
        FUN = function(x, nbytes) {
          # NULL generated by iconv() for NA_character_
          if (is.null(x)) {
            x <- writeBin(NA_integer_, raw())
          }
          length(x) <- nbytes
          return(x)
        },
        nbytes = datatype$nbytes
      )
    )
  } else {
    if (is.na(endian)) {
      endian <- "little"
    }
    writeBin(input, raw(), size = datatype$nbytes, endian = endian)
  }
}


# -- Variable-length UTF-8 ------------------------
`codec_vlen-utf8_encode` <- function(input, ...) {
  raw_nvalues <- writeBin(length(input), raw(), size = 4L, endian = "little")
  # charToRaw() converts NA_character_ to "NA"
  raw_strings <- lapply(input, function(x) charToRaw(enc2utf8(x)))
  raw_string_lens <- lapply(lengths(raw_strings), function(x) {
    writeBin(x, raw(), size = 4L, endian = "little")
  })

  raw_vlen_utf8 <- c(
    raw_nvalues,
    unlist(mapply(
      function(len, str) c(len, str),
      raw_string_lens,
      raw_strings
    ))
  )
  return(raw_vlen_utf8)
}

`codec_vlen-utf8_decode` <- function(input, chunk_dim, ...) {
  .Call("codec_vlen_utf8_decode_c", input, chunk_dim, PACKAGE = "Rarr")
}
